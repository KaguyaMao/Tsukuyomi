export const LOCALES = ["en", "zh"];

export function normalizeLocale(value) {
	const normalized = String(value || "").trim().toLowerCase().replaceAll("_", "-");
	if (normalized === "zh" || normalized.startsWith("zh-")) return "zh";
	if (normalized === "en" || normalized.startsWith("en-")) return "en";
	return undefined;
}

export function detectLocale(env = process.env, systemLocale) {
	const requested = normalizeLocale(env?.TSUKUYOMI_LANG || env?.TSUKUYOMI_LANGUAGE);
	if (requested) return requested;
	const candidates = [
		systemLocale,
		env?.LC_ALL,
		env?.LC_MESSAGES,
		env?.LANG,
	];
	for (const candidate of candidates) {
		const locale = normalizeLocale(candidate);
		if (locale) return locale;
	}
	return "en";
}

export function createTranslator(locale = "en") {
	const selected = normalizeLocale(locale) || "en";
	return (key, values = {}) => {
		const template = MESSAGES[selected][key] ?? MESSAGES.en[key] ?? key;
		return template.replace(/{{(\w+)}}/g, (_match, name) => String(values[name] ?? ""));
	};
}

export function getMessages(locale = "en") {
	const selected = normalizeLocale(locale) || "en";
	return { ...MESSAGES.en, ...MESSAGES[selected] };
}

export function formatCompactNumber(value, locale = "en") {
	if (value == null || !Number.isFinite(Number(value))) return "—";
	const number = Number(value);
	if (number === 0) return "0";
	try {
		return new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en-US", {
			notation: "compact",
			maximumFractionDigits: number < 10_000 ? 1 : 0,
		}).format(number);
	} catch {
		if (Math.abs(number) < 1_000) return String(Math.round(number));
		return `${(number / 1_000).toFixed(1)}K`;
	}
}

export function formatNumber(value, locale = "en") {
	if (value == null || !Number.isFinite(Number(value))) return "—";
	try {
		return new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en-US").format(Number(value));
	} catch {
		return String(value);
	}
}

export function formatPercent(value, locale = "en") {
	if (value == null || !Number.isFinite(Number(value))) return "—";
	try {
		return new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en-US", {
			maximumFractionDigits: 1,
		}).format(Number(value));
	} catch {
		return String(Math.round(Number(value)));
	}
}

export function formatDateTime(value, locale = "en") {
	const date = value instanceof Date ? value : new Date(value);
	if (!Number.isFinite(date.getTime())) return "—";
	try {
		return new Intl.DateTimeFormat(locale === "zh" ? "zh-CN" : "en-US", {
			dateStyle: "medium",
			timeStyle: "short",
		}).format(date);
	} catch {
		return date.toLocaleString();
	}
}

export function formatRelativeReset(value, locale = "en") {
	const date = value instanceof Date ? value : new Date(value);
	if (!Number.isFinite(date.getTime())) return "—";
	const now = Date.now();
	const diff = date.getTime() - now;
	if (diff <= 0) return locale === "zh" ? "即将重置" : "soon";
	const minutes = Math.max(1, Math.round(diff / 60_000));
	if (minutes < 60) return locale === "zh" ? `${minutes} 分钟后` : `in ${minutes}m`;
	const hours = Math.round(minutes / 60);
	if (hours < 24) return locale === "zh" ? `${hours} 小时后` : `in ${hours}h`;
	const days = Math.round(hours / 24);
	return locale === "zh" ? `${days} 天后` : `in ${days}d`;
}
